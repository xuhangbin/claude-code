const.Z0 = const.rho0 * const.c0;
const.nu = const.eta / const.rho0;
const.mu = const.kappa / (const.rho0 * const.Cv);
const.W = 30e-3;
const.L = 30e-3;
const.S = const.W * const.L;
const.dMin = 1e-3;
const.dMax = 8e-3;
